# ============================================================
# 规则顾问提示词（rules_template.py）
# ============================================================
# 【规则顾问 Agent 的职责】
#   在 GM 处理玩家行动之前，先做一步"规则预处理"：
#   - 判断行动类型（战斗/社交/探索等）
#   - 判断是否需要骰子检定（以及用什么技能、难度多少）
#   - 给出一句叙事指令（本回合应该发生的核心事件）
#
#   输出是"仅 GM 看"的元指令，不直接出现在游戏叙事里。
#   GM 读到这个预处理结果后，再生成面向玩家的叙事。
#
# 【为什么需要规则预处理？】
#   GM（大 LLM）需要同时管叙事、NPC、骰子、状态变化……负担很重。
#   让一个更小/更快的 LLM 先做规则判断，GM 只需要照着执行，
#   可以减少 GM 在规则细节上犯错（如忘记该掷骰、DC 设定不合理）。
#
# 【输出格式说明】
#   严格三行：
#   行动类型：[类型]
#   技能检定：无 | [技能] DC[数字]
#   叙事指令：[一句话]
#   不允许其他任何输出，方便后端按行解析。
# ============================================================
from dzmm.models.client import Message

# 规则顾问的提示词：任务非常明确，输出格式固定
_TEMPLATE = """你是 TRPG 规则顾问。分析玩家行动，输出规则预处理指令（仅 GM 看，不出现在叙事里）。

# 当前关键情境
{key_facts}

# 玩家行动
{current_action}

# 输出格式（严格三行，不要其他说明）
行动类型：战斗/社交/探索/潜行/施法/其他（选一个）
技能检定：无 | 或 [技能名] DC[数字]（如：力量检定 DC12）
叙事指令：一句话，本回合应该发生的核心事件

示例输出：
行动类型：战斗
技能检定：力量检定 DC12
叙事指令：PC 奋力推开厚重的铁门，身后的追兵越来越近。
"""


def build_rules_messages(key_facts: str, current_action: str) -> list[Message]:
    # 规则顾问只用 user 消息，不需要 system 消息（任务简单，格式固定）
    # key_facts：关键情境信息（包含 PC 属性、当前状态等），帮助判断技能 DC
    return [
        Message(
            role="user",
            content=_TEMPLATE.format(
                key_facts=key_facts.strip() or "（暂无）",
                current_action=current_action.strip(),
            ),
        )
    ]
