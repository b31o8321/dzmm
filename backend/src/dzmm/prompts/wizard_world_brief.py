"""v0.2.0 wizard step 1 — base world brief (returned as strict JSON)."""
# ============================================================
# 世界创建向导 - 第 1 步：生成基础世界简介（wizard_world_brief.py）
# ============================================================
# 【"向导"（Wizard）是什么？】
#   玩家创建新游戏时，如果不想从零开始写世界观，可以用"创建向导"。
#   向导是一系列步骤：玩家先选故事类型和主题关键词，
#   向导逐步生成世界简介 → 详细设定 → 角色原型 → NPC 等。
#   每一步都是一次独立的 LLM 调用，输出 JSON，方便前端渲染和用户编辑。
#
# 【第 1 步做什么？】
#   根据：故事类型（如"悬疑探案"）+ 主题（如"2091年反乌托邦城市"）
#   生成一份 80-150 字的"种子世界设定"：
#   - name：世界/故事的名字
#   - setting：时代背景和地理空间
#   - conflict：最核心的矛盾
#
#   这只是个"简介"（brief），后续的第 2 步会把它扩展成完整的世界观文档。
#
# 【为什么输出 JSON？】
#   前端可以解析 JSON，让用户单独编辑 name/setting/conflict 三个字段，
#   然后确认后进入下一步（生成详细世界观）。
#   如果是纯文本，前端就没法做分字段编辑了。
# ============================================================
from dzmm.models.client import Message

# 世界简介生成的系统提示词
_SYSTEM = """你是一位经验丰富的 TRPG 世界观设计师。

# 任务
根据玩家提供的「故事类型」和「主题」生成一份**简短的基础世界设定**，
作为后续详细设定 / 角色 / 剧本的种子。

# 输出格式（严格 JSON，**不要 markdown 代码块**，**不要前后加任何文字**）

{
  "name": "世界 / 故事的名字（6-20 字，一行）",
  "setting": "80-150 字：时代背景、地理空间、独有特征——例如：「2089 年的香港九龙城寨」「魔法已枯竭三百年的北方大陆」",
  "conflict": "80-150 字：本世界正在发生 / 即将爆发的最关键矛盾——派系战争 / 神权坍塌 / 灾后求生 / ..."
}

# 强约束
- 输出**必须**是合法 JSON，顶层是 `{...}`
- 必须包含 name / setting / conflict 三个字段，**字段名一字不差**
- 不要 ```json 代码块包裹
- 不要前后加「这是」「以下是」之类的解释
- 风格紧扣 genre 和 theme，不要写成空泛的奇幻
- conflict 必须命名至少一个 NPC（人物名）和一个地点（城市/街区/建筑名），\
不要泛指"某神秘人"/"某地点"。例如：
  ✓ "雨夜码头连续出现尸体；私家侦探陈墨衍发现警员张猛涉嫌掩盖。"
  ✗ "近期发生了一些怪事，需要调查。"
"""

# 每个已知类型的当下危机提示（注入 user message，引导 LLM 生成具体冲突）
_GENRE_CONFLICT_HINTS: dict[str, str] = {
    "悬疑探案": "近期 N 起相同手法的案件、警方压案、有目击者失踪",
    "英雄成长": "即将到来的威胁（特定名字的敌人 / 异常事件正在累积）",
    "政治阴谋": "派系冲突逼近临界点、阴谋揭露差一步、关键人物即将失势",
    "灾难求生": "灾变正在发生或刚刚开始，幸存者面临具体短缺",
    "恋爱攻略": "PC 与某具名 NPC 之间的关键关系障碍（婚约 / 误会 / 阶层差距）",
    "奇幻冒险": "古老封印的崩坏 / 失落物品被觊觎 / 神祇沉默",
    "赛博朋克": "企业争霸的次级冲突 / 黑色市场动荡 / 一个被泄露的秘密",
    "东方武侠": "门派恩怨 / 武林秘籍现世 / 朝廷压力 / 一桩被掩盖的旧案",
    "恐怖求生": "未知存在已经开始影响人群 / 安全圈在缩小 / 通讯失联",
}


def build_world_brief_messages(genre: str, theme: str) -> list[Message]:
    # 构建"生成世界简介"的消息列表
    # genre：故事类型（如"悬疑探案"、"政治阴谋"）
    # theme：玩家输入的主题关键词（可能很粗糙，如"科幻反乌托邦"）
    # 默认值兜底：如果玩家没填主题，用"（玩家未指定）"
    genre_str = genre.strip() or "悬疑探案"
    hint = _GENRE_CONFLICT_HINTS.get(genre_str)
    hint_line = (
        f"\n# 当下危机提示（conflict 字段请围绕以下要素展开）\n{hint}\n"
        if hint
        else ""
    )
    user = (
        f"# 故事类型\n{genre_str}\n\n"
        f"# 主题\n{theme.strip() or '（玩家未指定）'}\n"
        f"{hint_line}\n"
        "现在生成基础世界设定的 JSON。"
    )
    return [
        Message(role="system", content=_SYSTEM),
        Message(role="user", content=user),
    ]
