"""Wizard refine theme — expand a rough direction into a polished one-line theme."""
# ============================================================
# 世界创建向导 - 主题精炼（wizard_refine_theme.py）
# ============================================================
# 【主题精炼做什么？】
#   玩家在填写"故事主题"时，可能只写几个词，如"末日孤岛求生"或"科幻间谍"。
#   这些词太模糊，LLM 很难据此生成有特色的世界观。
#   主题精炼 Agent 把这个粗糙的方向精炼成一句"有画面感、有细节、点出矛盾"的主题描述。
#
# 【例子】
#   输入："科幻间谍"（很模糊）
#   输出："2157年的月面殖民地，三大公司用神经入侵技术互相渗透，
#         而被遗忘在服务器里的旧时代特工意外复活。"（有画面感、有具体细节）
#
# 【为什么要这一步？】
#   有了好的主题描述，第 1 步（生成世界简介）的输出质量会大幅提升。
#   这相当于"提示词工程"——先把模糊输入规范化，再喂给后续步骤。
#
# 【输出格式】
#   直接输出一句话（20-60字），不加引号，不加前后说明。
#   方便前端直接展示给用户确认或修改。
# ============================================================
from dzmm.models.client import Message

_SYSTEM = """你是 TRPG 故事策划师，擅长把模糊的想法精炼成有画面感的故事主题。

# 任务
玩家给了一个粗糙的故事方向（可能只有几个词或一句话），帮他精炼成一句**有画面感、有具体细节、点出核心矛盾或氛围**的主题描述（20-60字）。

# 要求
- 直接输出那一句话，不加任何前后说明、不加引号
- 保留玩家原意，用具体细节替换抽象词汇
- 要有画面感：能让人脑海中浮现具体场景
- 点出最核心的矛盾或情感张力
"""


def build_refine_theme_messages(genre: str, rough: str) -> list[Message]:
    # genre：故事类型（帮助 LLM 知道精炼的风格方向）
    # rough：玩家的粗糙输入（可能只是几个关键词）
    # 输出格式非常简单，直接给 user 消息，不需要额外格式说明
    user = f"题材：{genre.strip() or '自定义'}\n玩家方向：{rough.strip()}\n\n精炼后的主题描述："
    return [Message(role="system", content=_SYSTEM), Message(role="user", content=user)]
