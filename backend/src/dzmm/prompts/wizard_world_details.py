"""v0.2.0 wizard step 2 — expand brief into a full 600-1200 字 world markdown."""
# ============================================================
# 世界创建向导 - 第 2 步：扩展世界简介为完整文档（wizard_world_details.py）
# ============================================================
# 【第 2 步做什么？】
#   用户已经在第 1 步确认了世界简介（brief）。
#   现在把那个 80-150 字的简介扩展成 600-1200 字的完整世界观 Markdown 文档。
#   这份文档会成为游戏中 GM 的常驻参考资料（注入到每回合的 System Prompt 里）。
#
# 【为什么输出 Markdown 而不是 JSON？】
#   详细世界观是给 GM（LLM）读的，用 Markdown 格式可读性最好。
#   JSON 适合结构化数据（玩家编辑字段），
#   Markdown 适合长篇文本（GM 阅读和叙事参考）。
#   两种格式各有用途，这一步用 Markdown。
#
# 【四个固定章节】
#   地理与环境 / 社会与势力 / 风俗 / 关键地点
#   这四个章节是固定要求，确保每个世界都有足够的可玩元素：
#   - 地理：GM 可以描写场景
#   - 势力：为剧情冲突提供来源
#   - 风俗：增加世界的真实感和异质感
#   - 关键地点：玩家可以立刻去到的具体地方
# ============================================================
from dzmm.models.client import Message

_SYSTEM = """你是一位经验丰富的 TRPG 世界观设计师。

# 任务
玩家已经审阅过基础设定（brief）。现在把它**扩展**为一份完整、可玩的世界观文档。
最终输出 650-1400 字的 markdown，作为 GM 的常驻参考。

# 输出格式（严格 markdown，5 个二级标题，按顺序）

## 地理与环境
（150-300 字：地形 / 气候 / 文明分布 / 自然异象。具体到能让 GM 描写场景）

## 社会与势力
（150-300 字：3-5 个主要势力或阶层，列出名字 + 立场 + 利益冲突。可用 markdown 列表）

## 风俗
（80-200 字：信仰 / 禁忌 / 节庆 / 日常生活习惯——给场景增添异质感）

## 关键地点
（150-300 字：3-5 个有名称的地点，每个一行短描述，**不要长段**。GM 可以让 PC 立刻去到。
推荐用 markdown 列表 `- **名字**：一句描述`）

## 当下危机
（50-100 字：世界当前正在发生的一件**具体**冲突或谜团。必须具体到地点、人物或事件名字，不能抽象泛论。
这是 PC 入场时会第一个碰到的问题。

按类型提示（根据 brief 的类型选一个方向）：
- 悬疑探案：未解之谜、连环案件、失踪人物——在哪里、谁失踪了、现在到了哪一步
- 英雄成长：即将爆发的威胁、势力即将入侵——谁在入侵、什么时候到、PC 如何知道
- 政治阴谋：阴谋揭露的临界点、即将发生的政变——谁在幕后、哪个势力、下一步是什么
- 灾难求生：灾变刚开始或正在发生——具体灾变形式、已影响哪个地点、什么东西还没倒
- 恋爱攻略：PC 与某 NPC 之间的关键障碍或情感分水岭——是什么阻碍、谁知道这件事
- 其它类型：世界当前最紧迫的一个具体矛盾，写清楚名字、地点、事件进展）

# 强约束
- 严格 5 个 ## 标题，文字必须是上述五个，不要变体
- 不要 markdown 代码块包裹整体输出
- 不要前后寒暄
- 必须基于玩家已确认的 brief，不要扩写出与 brief 矛盾的内容
- 「当下危机」必须有专有名词（人名 / 地名 / 组织名），不允许纯抽象描述
"""

# 按类型推导的危机提示（注入到用户消息）
_GENRE_CRISIS_HINTS: dict[str, str] = {
    "悬疑探案": "「当下危机」请围绕一件未解的案件或失踪事件展开，写明嫌疑人名字或失踪地点。",
    "英雄成长": "「当下危机」请描述一个具名势力的入侵或威胁，写明距离爆发还有多少时间。",
    "政治阴谋": "「当下危机」请描述一场正在逼近的政变或阴谋揭露临界点，写明主谋势力或人物。",
    "灾难求生": "「当下危机」请描述灾变的当前状态（刚开始/蔓延中），写明受灾的具体地点。",
    "恋爱攻略": "「当下危机」请描述 PC 与某 NPC 之间最核心的情感障碍，写明 NPC 名字和障碍来源。",
}
_GENRE_CRISIS_FALLBACK = "「当下危机」请写出当前世界最紧迫的一个具体矛盾，包含专有名词（人名 / 地名 / 组织名）。"


def build_world_details_messages(brief_md: str, genre: str = "") -> list[Message]:
    # 第 2 步的输入：用户在第 1 步确认的世界简介（brief_md）
    # brief_md 可能是 JSON 格式的 brief，或者用户直接编辑后的文本
    # [:2000]：截断，防止 brief 太长（正常 brief 不超过 500 字，2000 是安全边界）
    brief = brief_md.strip()[:2000] or "（玩家未提供 brief）"
    crisis_hint = _GENRE_CRISIS_HINTS.get(genre, _GENRE_CRISIS_FALLBACK)
    user = (
        "# 已确认的基础设定（brief）\n"
        f"{brief}\n\n"
        f"类型提示：{crisis_hint}\n\n"
        "现在扩展为完整世界观。"
    )
    return [
        Message(role="system", content=_SYSTEM),
        Message(role="user", content=user),
    ]
