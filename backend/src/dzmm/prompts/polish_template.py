# ============================================================
# 文学润色提示词（polish_template.py）
# ============================================================
# 【润色 Agent 的职责】
#   GM 生成的叙事文本质量有时偏"流水账"。润色 Agent 可以把
#   GM 的原始叙事文本处理得更有文学感：
#   - 优化句式和节奏
#   - 加强感官细节
#   - 但绝对不改变情节内容或事件结果
#
# 【为什么不直接让 GM 写好一点？】
#   "让 GM 同时管剧情逻辑 + 写漂亮的文学语言"会分散注意力，
#   容易导致 GM 在追求文学性时忘记规则（如漏掉骰子、忘记更新状态）。
#   分离关注点：GM 负责逻辑正确，润色 Agent 负责语言美化。
#
# 【使用场景】
#   这是可选的后处理步骤。开启润色功能时，
#   GM 输出的 <narrative> 内容会被送到润色 Agent 处理一遍，
#   然后再展示给玩家。
#
# 【长度控制：90%-120%】
#   不允许润色 Agent 大量扩写（>120%），防止节奏被拖慢；
#   也不允许大量删减（<90%），防止丢失重要信息。
# ============================================================
from dzmm.models.client import Message

# 润色 Agent 的提示词：只允许改语言，不允许改内容
_TEMPLATE = """你是 TRPG 文学润色师。把下面的跑团 GM 叙事文本润色得更有文学质感，不改变任何情节内容、NPC 对话、或事件结果。

润色原则：
- 优化句式和节奏，避免平铺直叙
- 加强感官细节（视觉/听觉/触觉），但不添加新信息
- 保持原有语气和风格（暗黑/治愈/写实等）
- 保留所有专有名词（人名/地名）原样
- 不添加新角色、新道具、新剧情

# 原文
{narrative}

直接输出润色后的文本，不要任何解释。长度控制在原文的 90%-120% 之间。
"""


def build_polish_messages(narrative: str) -> list[Message]:
    # 润色 Agent 只用 user 消息（无需 system 消息）
    # 输入：GM 的原始叙事文本  输出：润色后的文本
    return [
        Message(
            role="user",
            content=_TEMPLATE.format(narrative=narrative.strip()),
        )
    ]
