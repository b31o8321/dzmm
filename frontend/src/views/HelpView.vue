## 检定规则（dice）

GM 在不确定结果时投 d20 + DC 判定：

- 属性 8-10 → DC 12（中等难度）
- 11-13 → DC 14
- 14-15 → DC 15
- 16+ → DC 17（高属性 = 体感更容易过）

